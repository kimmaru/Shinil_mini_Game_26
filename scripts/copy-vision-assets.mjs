// Prebuild: vendor the MediaPipe wasm fileset, the pose model, and the font files
// into /public so everything is served from our own origin.
//
// Why self-host instead of CDN:
//   1. The CSP in vercel.json is `connect-src 'self'`, which is the provable
//      non-exfiltration guarantee the 개인정보 안내 page claims. A CDN font or
//      model fetch would make that claim false.
//   2. 14.7 MB of wasm over a flaky school network is the worst load-time risk
//      in this app. Our own origin + Brotli + immutable caching is the fix.
import { createHash } from 'node:crypto';
import { createWriteStream } from 'node:fs';
import { cp, mkdir, readdir, stat, writeFile, readFile } from 'node:fs/promises';
import { pipeline } from 'node:stream/promises';
import { Readable } from 'node:stream';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const log = (...a) => console.log('[vision-assets]', ...a);

/** Pose models. Sizes are from the research brief and are asserted after download. */
const MODELS = [
  {
    file: 'pose_landmarker_lite.task',
    bytes: 5_777_746,
    url: 'https://storage.googleapis.com/mediapipe-models/pose_landmarker/pose_landmarker_lite/float16/latest/pose_landmarker_lite.task',
  },
  {
    file: 'pose_landmarker_full.task',
    bytes: 9_398_198,
    url: 'https://storage.googleapis.com/mediapipe-models/pose_landmarker/pose_landmarker_full/float16/latest/pose_landmarker_full.task',
    optional: true,
  },
];

async function exists(p) {
  try { await stat(p); return true; } catch { return false; }
}

async function copyWasm() {
  const src = join(ROOT, 'node_modules/@mediapipe/tasks-vision/wasm');
  const dst = join(ROOT, 'public/wasm');
  if (!(await exists(src))) {
    log('SKIP wasm — @mediapipe/tasks-vision not installed yet');
    return;
  }
  await mkdir(dst, { recursive: true });
  await cp(src, dst, { recursive: true });
  const files = await readdir(dst);
  log(`wasm -> public/wasm (${files.length} files: ${files.join(', ')})`);
}

async function download({ file, url, bytes, optional }) {
  const dst = join(ROOT, 'public/models', file);
  if (await exists(dst)) {
    const { size } = await stat(dst);
    if (size === bytes) { log(`model ${file} already present (${size} bytes)`); return; }
    log(`model ${file} size mismatch (${size} != ${bytes}) — refetching`);
  }
  await mkdir(dirname(dst), { recursive: true });
  log(`downloading ${file} (~${(bytes / 1e6).toFixed(1)} MB) from ${new URL(url).host}`);
  const res = await fetch(url);
  if (!res.ok) {
    const msg = `${file}: HTTP ${res.status} from ${url}`;
    if (optional) { log(`SKIP optional ${msg}`); return; }
    throw new Error(msg);
  }
  await pipeline(Readable.fromWeb(res.body), createWriteStream(dst));
  const { size } = await stat(dst);
  const sha = createHash('sha256').update(await readFile(dst)).digest('hex');
  log(`model ${file}: ${size} bytes, sha256 ${sha.slice(0, 16)}…`);
  if (size !== bytes) log(`  ⚠ expected ${bytes} bytes — upstream may have republished the model`);
}

async function copyFonts() {
  const dst = join(ROOT, 'public/fonts');
  await mkdir(dst, { recursive: true });
  const src = join(ROOT, 'node_modules/pretendard/dist/web/variable/woff2');
  if (await exists(src)) {
    await cp(src, join(dst, 'pretendard'), { recursive: true });
    const n = (await readdir(join(dst, 'pretendard'))).length;
    log(`fonts -> public/fonts/pretendard (${n} files)`);
  } else {
    log('SKIP pretendard woff2 — package layout not found; fonts.css falls back to system-ui');
  }
  // fonts.css is generated, never hand-edited, so the @font-face urls always
  // match whatever actually landed in public/fonts.
  const hasVar = await exists(join(dst, 'pretendard/PretendardVariable.woff2'));
  await writeFile(join(dst, 'fonts.css'), hasVar ? FONTS_CSS_LOCAL : FONTS_CSS_FALLBACK, 'utf8');
  log(`fonts.css written (${hasVar ? 'self-hosted Pretendard' : 'system fallback only'})`);
}

const FONTS_CSS_LOCAL = `/* GENERATED by scripts/copy-vision-assets.mjs — do not edit. */
@font-face {
  font-family: 'Pretendard Variable';
  font-weight: 45 920;
  font-style: normal;
  font-display: swap;
  src: url('/fonts/pretendard/PretendardVariable.woff2') format('woff2-variations');
}
`;

const FONTS_CSS_FALLBACK = `/* GENERATED by scripts/copy-vision-assets.mjs — Pretendard not vendored.
   The app's --font-ui stack falls through to system Korean faces. */
`;

await copyWasm();
await copyFonts();
for (const m of MODELS) await download(m);
log('done');
